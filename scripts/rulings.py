"""The rulings log: one line for every rule of David's in docs/rules/*.md, newest first, with the rulings that
replaced older ones on top (docs/rules/superseded.json). Writes docs/RULINGS.md; never edit that file by hand.

    python3 -I scripts/rulings.py           # rewrite docs/RULINGS.md
    python3 -I scripts/rulings.py --check   # CI: RULINGS.md is current, and no rule or skill copy still points to a
                                            # superseded model (the "stale" phrases in superseded.json)

When David gives a new ruling: write it into its rule file with his words and the date (review.md, "a new rule"),
add a core line to docs/rules/CORE_SKILL.md, and if it replaces an older ruling add an entry to superseded.json,
mark the old bullet "superseded" and run this script.
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'RULINGS.md')
MON = {'Sep': 9, 'September': 9, 'Oct': 10, 'October': 10, 'Nov': 11, 'November': 11, 'Dec': 12, 'December': 12}
DATE = re.compile(r'(\d{1,2}) (Sep|September|Oct|October|Nov|November|Dec|December) (2026)')

def rulings():
    out = []
    for f in sorted(glob.glob(os.path.join(ROOT, 'docs', 'rules', '*.md'))):
        if f.endswith('CORE_SKILL.md'): continue
        for i, l in enumerate(open(f, encoding='utf-8'), 1):
            if not l.startswith('- ') or 'David' not in l: continue
            m = re.search(r'\*\*(.+?)\*\*', l)
            title = re.sub(r'[`*]', '', m.group(1) if m else re.split(r'(?<=[.;:])\s', l[2:])[0]).strip().rstrip('.:')
            if len(title) > 110: title = title[:110].rsplit(' ', 1)[0] + ' …'
            ds = sorted({(int(y), MON[mo], int(d)) for d, mo, y in DATE.findall(l)})
            q = re.search(r'David[^“"]{0,40}[“"]([^”"]{8,})[”"]', l)
            quote = (q.group(1) if len(q.group(1)) < 200 else q.group(1)[:200].rsplit(' ', 1)[0] + ' …') if q else ''
            out.append(dict(file=os.path.relpath(f, ROOT), line=i, title=title, dates=ds, quote=quote,
                            superseded='superseded' in l.lower()))
    return out

def fmt(d): return f'{d[2]} {[k for k, v in MON.items() if v == d[1] and len(k) == 3][0]} {d[0]}'

def render():
    sup = json.load(open(os.path.join(ROOT, 'docs', 'rules', 'superseded.json'), encoding='utf-8'))
    R = rulings()
    L = ['# Rulings log', '',
         'Generated by `python3 -I scripts/rulings.py` from docs/rules/*.md; do not edit by hand. Every rule of David\'s, '
         'newest first, with the rule file and line where its full wording is. Read the **Replaced** list before any '
         'task: an older ruling there no longer holds, and nothing may follow it.', '',
         '## Replaced rulings', '', '| Date | No longer | Now | Rule file |', '|---|---|---|---|']
    L += [f"| {s['date']} | {s['old']} | {s['new']} | {s['where']} |" for s in sup]
    L += ['', '## Every ruling, newest first', '', '| Latest date | Ruling | David\'s words | Where |', '|---|---|---|---|']
    dated = sorted([r for r in R if r['dates']], key=lambda r: (r['dates'][-1], r['file'], r['line']), reverse=True)
    for r in dated:
        when = ', '.join(fmt(d) for d in r['dates'])
        L.append(f"| {when} | {r['title']}{' (partly replaced: see above)' if r['superseded'] else ''} | {r['quote']} | {r['file']}:{r['line']} |")
    L += ['', '## Rulings without a date (October 2026, from the first parashot)', '', '| Ruling | David\'s words | Where |', '|---|---|---|']
    L += [f"| {r['title']} | {r['quote']} | {r['file']}:{r['line']} |" for r in R if not r['dates']]
    return '\n'.join(x.replace('\n', ' ') for x in L) + '\n'

def stale_hits():
    sup = json.load(open(os.path.join(ROOT, 'docs', 'rules', 'superseded.json'), encoding='utf-8'))
    phrases = [p for s in sup for p in s.get('stale', [])]
    files = glob.glob(os.path.join(ROOT, 'docs', 'rules', '*.md')) + glob.glob(os.path.join(ROOT, 'docs', 'skills', '*.md')) \
        + [os.path.join(ROOT, 'docs', 'HANDOFF.md')]
    hits = []
    for f in files:
        for i, l in enumerate(open(f, encoding='utf-8'), 1):
            for p in phrases:
                if p.lower() in l.lower() and 'superseded' not in l.lower():
                    hits.append(f'{os.path.relpath(f, ROOT)}:{i}: still says "{p}" (superseded)')
    return hits

if __name__ == '__main__':
    text = render()
    if sys.argv[1:] == ['--check']:
        bad = []
        if not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text:
            bad.append('docs/RULINGS.md is out of date: run python3 -I scripts/rulings.py')
        bad += stale_hits()
        print('\n'.join(bad) or 'rulings: current; no superseded model is still pointed to')
        sys.exit(1 if bad else 0)
    open(OUT, 'w', encoding='utf-8').write(text)
    print(f'{OUT}: {text.count(chr(10))} lines')
    for h in stale_hits(): print(h)
